#!/usr/bin/env node
/**
 * Runs the compatibility matrix in compat/matrix.json.
 *
 *   pnpm compat                      # every case
 *   pnpm compat react zod@3.25.76    # only some libraries or cases
 *   pnpm compat --report             # only regenerate COMPATIBILITY.md from compat/results.json
 *
 * Each case runs in a throwaway copy of the repo (your lockfile is never touched):
 * the library is pinned with pnpm overrides, then the listed packages are built,
 * typechecked and unit tested; libraries marked `e2e` also run the example's
 * Playwright suite. Results are merged into compat/results.json and rendered to
 * COMPATIBILITY.md.
 */
import { execSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const matrix = JSON.parse(readFileSync(join(root, "compat/matrix.json"), "utf8"));
const resultsPath = join(root, "compat/results.json");
const results = existsSync(resultsPath) ? JSON.parse(readFileSync(resultsPath, "utf8")) : {};

const args = process.argv.slice(2);
const reportOnly = args.includes("--report");
const filters = args.filter((a) => !a.startsWith("--"));

function selected(lib, version) {
  if (!filters.length) return true;
  return filters.some((f) => f === lib.name || f === `${lib.name}@${version}`);
}

function run(cmd, cwd, log) {
  log.push(`$ ${cmd}`);
  try {
    log.push(execSync(cmd, { cwd, stdio: "pipe", encoding: "utf8", env: { ...process.env, CI: "1", FORCE_COLOR: "0" } }));
    return true;
  } catch (error) {
    log.push(String(error.stdout ?? ""), String(error.stderr ?? ""));
    return false;
  }
}

function overridesFor(lib, version) {
  const major = version.split(".")[0];
  const overrides = { [lib.name]: version };
  for (const [name, spec] of Object.entries(lib.companions ?? {})) {
    overrides[name] = spec === "$version" ? version : spec === "$major" ? `^${major}` : spec;
  }
  return overrides;
}

function runCase(lib, version) {
  const dir = mkdtempSync(join(tmpdir(), "warpstate-compat-"));
  const log = [];
  const started = Date.now();
  const outcome = { status: "fail", stage: "copy", durationS: 0, resolved: null };
  try {
    cpSync(root, dir, {
      recursive: true,
      filter: (src) => !/(^|\/)(node_modules|dist|\.git|test-results|playwright-report|coverage)(\/|$)/.test(src.slice(root.length)),
    });
    const pkgPath = join(dir, "package.json");
    const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
    pkg.pnpm = { ...pkg.pnpm, overrides: { ...pkg.pnpm?.overrides, ...overridesFor(lib, version) } };
    writeFileSync(pkgPath, JSON.stringify(pkg, null, 2));

    const filters = lib.packages.map((p) => `--filter "${p}..."`).join(" ");
    const testFilters = lib.packages.map((p) => `--filter "${p}"`).join(" ");
    const stages = [
      ["install", "pnpm install --no-frozen-lockfile --prefer-offline"],
      ["build", `pnpm ${filters} build`],
      ["typecheck", `pnpm ${testFilters} typecheck`],
      ["test", `pnpm ${testFilters} test`],
    ];
    if (lib.e2e) {
      stages.push(["e2e-build", `pnpm --filter "example-react-tanstack..." build`]);
      stages.push(["e2e", "pnpm --filter example-react-tanstack exec playwright test"]);
    }
    for (const [stage, cmd] of stages) {
      outcome.stage = stage;
      if (!run(cmd, dir, log)) throw new Error(`${stage} failed`);
    }

    // Report the version that was actually installed for the first package.
    const pkgDir = execSync(`pnpm --filter "${lib.packages[0]}" exec pwd`, { cwd: dir, encoding: "utf8" }).trim();
    const installed = join(pkgDir, "node_modules", lib.name, "package.json");
    outcome.resolved = existsSync(installed) ? JSON.parse(readFileSync(installed, "utf8")).version : version;
    outcome.status = outcome.resolved === version ? "pass" : "mismatch";
    outcome.stage = "done";
  } catch {
    const tail = log.join("\n").split("\n").filter(Boolean).slice(-40).join("\n");
    outcome.log = tail;
  } finally {
    outcome.durationS = Math.round((Date.now() - started) / 1000);
    rmSync(dir, { recursive: true, force: true });
  }
  return outcome;
}

function render() {
  const date = new Date().toISOString().slice(0, 10);
  const lines = [
    "# Compatibility",
    "",
    "Generated by `pnpm compat` from [`compat/matrix.json`](compat/matrix.json). Each cell pins one library",
    "version (everything else at the versions in the lockfile), then builds, typechecks and unit-tests the",
    "packages that depend on it. Rows marked **e2e** also run the example app's Playwright suite.",
    "",
    "✅ pass · ❌ fail (stage in parentheses) · ⚠️ installed version differs · — not run yet",
    "",
  ];
  const categories = [...new Set(matrix.libraries.map((l) => l.category ?? "Other"))];
  for (const category of categories) {
    lines.push(`## ${category}`, "", "| Library | Declared peer range | Version | Result | Checked | Covers |", "| --- | --- | --- | --- | --- | --- |");
    for (const lib of matrix.libraries.filter((l) => (l.category ?? "Other") === category)) {
    for (const version of lib.versions) {
      const r = results[`${lib.name}@${version}`];
      const cell = !r ? "—" : r.status === "pass" ? "✅" : r.status === "mismatch" ? `⚠️ got ${r.resolved}` : `❌ (${r.stage})`;
      const covers = `${lib.packages.join(", ")}${lib.e2e ? " + **e2e**" : ""}`;
      lines.push(`| \`${lib.name}\` | \`${lib.peerRange.replace(/\|/g, "\\|")}\` | ${version} | ${cell} | ${r?.date ?? "—"} | ${covers} |`);
    }
    }
    const notes = matrix.libraries.filter((l) => (l.category ?? "Other") === category && l.why);
    if (notes.length) lines.push("", ...notes.map((l) => `- \`${l.name}\`: ${l.why}`));
    lines.push("");
  }
  lines.push(
    "Always tested in CI on every push: the latest version of each library (see the lockfile) with the full unit and e2e suites.",
    "",
    "## Extending the matrix",
    "",
    "1. Add a version (or a new library entry) to `compat/matrix.json`.",
    "2. Run `pnpm compat <library>` locally, or let the `compat` CI workflow run it.",
    "3. If a version fails, either fix the integration or narrow the package's `peerDependencies` range.",
    "",
    `_Last generated: ${date}._`,
    "",
  );
  writeFileSync(join(root, "COMPATIBILITY.md"), lines.join("\n"));
}

if (!reportOnly) {
  for (const lib of matrix.libraries) {
    for (const version of lib.versions) {
      if (!selected(lib, version)) continue;
      process.stdout.write(`${lib.name}@${version} … `);
      const outcome = runCase(lib, version);
      results[`${lib.name}@${version}`] = { ...outcome, date: new Date().toISOString().slice(0, 10) };
      console.log(`${outcome.status}${outcome.status === "fail" ? ` at ${outcome.stage}` : ""} (${outcome.durationS}s)`);
      if (outcome.log) console.log(outcome.log.split("\n").map((l) => `    ${l}`).join("\n"));
      writeFileSync(resultsPath, `${JSON.stringify(results, null, 2)}\n`);
    }
  }
}
render();
const failed = Object.entries(results).filter(([, r]) => r.status !== "pass");
if (!reportOnly && failed.length) {
  console.log(`\n${failed.length} case(s) not passing: ${failed.map(([k]) => k).join(", ")}`);
  process.exitCode = 1;
}
